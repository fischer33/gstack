import { BASE, OUT, launch, register } from './lib.mjs';
const b = await launch();
const p = await b.newPage({ viewport: { width: 1280, height: 800 } });
const errs = []; p.on('pageerror', e => errs.push(e.message)); p.on('console', m => m.type() === 'error' && !/Failed to load resource/.test(m.text()) && errs.push(m.text()));
let fails = 0;
const ok = (n, c) => { if (!c) fails++; console.log(c ? 'PASS' : 'FAIL', n); };
const email = 'e2e' + Date.now() + '@example.com';
await p.goto(`${BASE}/`); await p.waitForSelector('h1');
await p.screenshot({ path: OUT + 'landing.png' });
ok('Landing zeigt Headline', /Gestalte/.test(await p.textContent('h1')));
await p.goto(`${BASE}/app`); await p.waitForURL('**/login');
ok('/app ohne Login -> /login', true);
await p.goto(`${BASE}/register`);
await p.fill('#email', 'kaputt'); await p.fill('#password', 'kurz1'); await p.click('button[type=submit]');
await p.waitForSelector('#email-err, #password-err');
ok('Validierungsfehler sichtbar', (await p.textContent('#password-err').catch(()=>'')).includes('8') || (await p.textContent('#email-err').catch(()=>'')).length > 0);
await p.fill('#name', 'Ada'); await p.fill('#email', email); await p.fill('#password', 'correct-horse-1'); await p.click('button[type=submit]');
await p.waitForURL('**/app'); ok('Registrierung -> /app', /Was möchtest du gestalten, Ada/.test(await p.textContent('h1')));
await p.reload(); await p.waitForSelector('h1'); ok('Session überlebt Reload', /Was möchtest du gestalten, Ada/.test(await p.textContent('h1')));
await p.click('button[aria-label=Dunkel]'); ok('Dark Mode aktiv', await p.evaluate(() => document.documentElement.classList.contains('dark')));
await p.screenshot({ path: OUT + 'app-dark.png' });
await p.reload(); ok('Dark Mode bleibt nach Reload', await p.evaluate(() => document.documentElement.classList.contains('dark')));
await p.click('button[aria-label=Konto]'); await p.click('[role=menuitem]:has-text("Abmelden")'); await p.waitForURL('**/login'); ok('Logout -> /login', true);
await p.fill('#email', email); await p.fill('#password', 'falsch-falsch'); await p.click('button[type=submit]');
await p.waitForSelector('[role=alert]'); ok('Falsches Passwort -> Fehlermeldung', /falsch/.test(await p.textContent('[role=alert]')));
await p.screenshot({ path: OUT + 'login-error-dark.png' });
await p.fill('#password', 'correct-horse-1'); await p.click('button[type=submit]');
await p.waitForURL('**/app'); ok('Login -> /app', true);
await p.click('button[aria-label=Hell]');
await p.context().clearCookies(); await p.goto(`${BASE}/login?error=google`);
await p.waitForSelector('[role=alert]'); ok('?error=google zeigt Hinweis', /Google/.test(await p.textContent('[role=alert]')));
await p.setViewportSize({ width: 390, height: 800 }); await p.goto(`${BASE}/`); await p.screenshot({ path: OUT + 'landing-mobile.png' });
ok('Mobil: kein horizontaler Scroll', await p.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
ok('Keine Konsolenfehler', errs.length === 0); if (errs.length) console.log(errs);
console.log(fails ? fails + ' FEHLER' : 'ALLES BESTANDEN');
process.exitCode = fails ? 1 : 0;
await b.close();
